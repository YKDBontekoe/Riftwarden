// Service worker for offline play (architecture v2 section 11), generated at build time with the build's file list.
// Hashed assets are cache-first (they never change); index.html is network-first with the cached copy as the offline
// fallback; other origins (the API) are never intercepted. A new build gets a new cache and removes the old ones.
import type { Plugin } from 'vite';

export function serviceWorker(): Plugin {
  return {
    name: 'riftwarden-sw',
    apply: 'build',
    generateBundle(_options, bundle) {
      const files = Object.keys(bundle).filter((f) => !f.endsWith('.map'));
      const version = files.filter((f) => f.startsWith('assets/')).sort().join('|');
      let h = 2166136261;
      for (let i = 0; i < version.length; i++) h = Math.imul(h ^ version.charCodeAt(i), 16777619) >>> 0;
      const source = `// Generated by apps/client/sw-plugin.ts
const CACHE = 'riftwarden-${h.toString(36)}';
const SHELL = ['./', './index.html'];
const ASSETS = ${JSON.stringify(files.filter((f) => f.startsWith('assets/')).map((f) => './' + f))};

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    await cache.addAll(SHELL);
    // Assets one by one: a single failure must not cancel the install.
    await Promise.allSettled(ASSETS.map((a) => cache.add(a)));
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) if (key.startsWith('riftwarden-') && key !== CACHE) await caches.delete(key);
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    event.respondWith((async () => {
      try {
        const fresh = await fetch(req);
        const cache = await caches.open(CACHE);
        cache.put('./index.html', fresh.clone());
        return fresh;
      } catch {
        return (await caches.match('./index.html', { ignoreVary: true })) ?? Response.error();
      }
    })());
    return;
  }
  if (url.pathname.includes('/assets/')) {
    event.respondWith((async () => {
      const hit = await caches.match(req, { ignoreVary: true });
      if (hit) return hit;
      const res = await fetch(req);
      if (res.ok) (await caches.open(CACHE)).put(req, res.clone());
      return res;
    })());
  }
});
`;
      this.emitFile({ type: 'asset', fileName: 'sw.js', source });
    },
  };
}
