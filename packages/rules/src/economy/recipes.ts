/** Each superior-or-better craft in the same market rotation costs this much more than the last (capped). */
export const HEAVY_ESCALATION = { step: 0.25, max: 12 } as const;

/** Cost multiplier of the next heavy craft after `n` heavy crafts this rotation. */
export const escalation = (q: QualityDef | undefined, n: number): number => (q?.heavy ? 1 + HEAVY_ESCALATION.step * Math.min(HEAVY_ESCALATION.max, Math.max(0, Math.floor(n))) : 1);

/**
 * Cost of one craft of an item recipe at a quality grade and item level. Salvage/credits follow the level factor,
 * components +50% per 25 levels, rift shards +1 per 20 levels; `heavyCrafts` = heavy crafts this rotation.
 */
export function craftCost(recipe: Recipe, quality: QualityDef | undefined, level: number, heavyCrafts = 0): Cost {
  if (recipe.output.kind === 'material') return { ...recipe.output.take };
  if (!quality) return {};
  const lvl = clampLevel(level);
  const f = levelFactor(level) * recipe.costMult;
  const compF = 1 + 0.5 * Math.floor((lvl - 1) / 25);
  const esc = escalation(quality, heavyCrafts);
  const out: Cost = {};
  for (const k of RESOURCE_KEYS) {
    const v = quality.cost[k] ?? 0;
    if (!v) continue;
    const base = k === 'components' ? v * compF : k === 'shards' ? v + Math.floor((lvl - 1) / 20) : v * f;
    out[k] = Math.max(1, Math.round(base * esc));
  }
  return out;
}

export function unlockedFor(recipe: Recipe, quality: QualityDef | undefined, tierUnlocked: number): { ok: true } | { ok: false; reason: string } {
  const need = Math.max(recipe.unlockTier, recipe.output.kind === 'item' ? (quality?.unlockTier ?? 99) : 1);
  return tierUnlocked >= need ? { ok: true } : { ok: false, reason: `Requires Rift Level ${need} unlocked` };
}

/** Exact rarity odds of a quality grade (UI "possible rarity" readout). */
export function qualityOdds(q: QualityDef): { id: RarityId; p: number }[] {
  const all = rarityOdds(q.luck, q.min);
  const hi = rarity(q.max).index;
  const lo = rarity(q.min).index;
  const inRange = RARITIES.filter((r) => r.index >= lo && r.index <= hi);
  const total = inRange.reduce((s, r) => s + all[r.id], 0);
  // Mass above the window collapses onto its top rarity (same rule as generation below).
  const above = RARITIES.filter((r) => r.index > hi).reduce((s, r) => s + all[r.id], 0);
  return inRange.map((r) => ({ id: r.id, p: (all[r.id] + (r.index === hi ? above : 0)) / (total + above) }));
}

function rollQualityRarity(rand: () => number, q: QualityDef): RarityId {
  const r = rollRarity(rand, q.luck, q.min);
  return rarity(r).index > rarity(q.max).index ? q.max : r;
}

/** Bases a recipe can produce (weapon family restricts chassis; module recipes are one base). */
export function recipeBases(recipe: Recipe): BaseDef[] {
  const o = recipe.output;
  if (o.kind !== 'item') return [];
  if (o.moduleBase) return BASES.filter((b) => b.id === o.moduleBase);
  return basesFor(o.category).filter((b) => !o.family || b.weapon?.family === o.family);
}

/** Generate the crafted item (deterministic for a seed). */
export function fabricate(recipe: Recipe, q: QualityDef, level: number, seed: number, uid: string, rand: () => number, now = Date.now(), locks: readonly string[] = []): ItemInstance | null {
  if (recipe.output.kind !== 'item') return null;
  const base = pickWeighted(recipeBases(recipe), (b) => Math.max(0.0001, b.weight), rand);
  if (!base) return null;
  return generateItem({ uid, seed, level, rarity: rollQualityRarity(rand, q), baseId: base.id, source: 'crafted', now, componentLocks: locks });
}
