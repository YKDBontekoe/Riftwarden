/**
 * Fabrication recipes (pure data + generation).
 *
 * A recipe picks WHAT is made (category, optionally a weapon family or module type) and a
 * QUALITY grade picks HOW GOOD it can be (rarity window, luck, cost, unlock). The output
 * is generated by the same generator as enemy loot (source 'crafted'), at the player's
 * progress level, so crafted gear follows every affix/tier/rarity rule of dropped gear.
 * Exotics cannot be fabricated. Grades open with Rift Levels (the same gates as drops: epics from RL 3, legendaries
 * from RL 7); masterwork and apex also cost rift shards, and every superior-or-better craft in one market rotation
 * costs 25% more than the last (`HEAVY_ESCALATION`), so crafting is a strong but expensive long-term sink.
 */
export type QualityId = 'standard' | 'refined' | 'superior' | 'masterwork' | 'apex';

export interface QualityDef {
  id: QualityId;
  label: string;
  min: RarityId;
  max: RarityId;
  /** Rarity luck inside the window (< 1 favours the low end). */
  luck: number;
  /** Cost at item level 1 (salvage/credits grow with levelFactor, components per 25 levels). */
  cost: Cost;
  /** Highest unlocked Rift Level required. */
  unlockTier: number;
  /** Counts toward the per-rotation escalation (superior and better). */
  heavy?: boolean;
  blurb: string;
}

