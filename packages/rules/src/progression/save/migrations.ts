import { emptyStructure } from '../../home/build/model';
import { baseDef } from '../../loot/bases';
import { isRarity, rarity } from '../../loot/rarity';
import { STARTING_CREDITS } from '../../economy/config';
import { SAVE_VERSION } from './types';
import { Obj, arr, obj } from './coerce';
import { createDefaultSave } from './defaults';

// ------------------------------------------------------------------ migrations

/**
 * MIGRATIONS[n] upgrades a raw version-n payload to version n+1. Add an entry here
 * (and bump SAVE_VERSION) whenever the stored shape changes incompatibly.
 */
export const MIGRATIONS: Record<number, (data: Obj) => Obj> = {
  /**
   * v1 (M1) -> v2 (M2): items gain generated stats (sanitizeItem upgrades the legacy
   * shape deterministically), the unused 'module' slot is removed (its item, if any, goes
   * to storage), storage capacity becomes STORAGE_CAPACITY + purchased expansions, and
   * loadout presets are introduced.
   */
  1: (d) => {
    const out: Obj = { ...d };
    const lo = { ...obj(d.loadout) };
    const storage = { ...obj(d.storage) };
    const uids = arr(storage.uids).filter((u): u is string => typeof u === 'string');
    if (typeof lo.module === 'string') uids.push(lo.module);
    delete lo.module;
    out.loadout = lo;
    out.storage = { expansions: 0, uids };
    out.presets = [];
    return out;
  },
  /**
   * v2 (M2) -> v3 (M3): weapons gain a default component build (stats untouched) and the
   * M3 socket count of their rarity; other categories lose their (never functional)
   * sockets; the unused `modules` uid list becomes `socketed` (all empty).
   */
  2: (d) => {
    const out: Obj = { ...d };
    out.items = arr(d.items).map((v) => {
      const it = { ...obj(v) };
      const isWeapon = it.category === 'weapon' || baseDef(typeof it.defId === 'string' ? it.defId : '')?.category === 'weapon';
      it.sockets = isWeapon && isRarity(it.rarity) ? rarity(it.rarity).sockets : 0;
      delete it.modules;
      it.socketed = [];
      return it;
    });
    return out;
  },
  /**
   * v3 (M3) -> v4 (M4): persistent economy. Adds credits (with the commissioning stipend)
   * and advanced components; merchant stock and economy state are generated by sanitize.
   * Items are untouched (engineering fields default to "none").
   */
  3: (d) => {
    const out: Obj = { ...d };
    const res = obj(d.resources);
    out.resources = { salvage: res.salvage, credits: STARTING_CREDITS, components: 0, shards: 0 };
    delete out.market;
    delete out.economy;
    return out;
  },
  /**
   * v4 (M4) -> v5 (M5): permanent tower blueprints. Nothing is rerolled or removed; the player starts
   * with only the starter parts researched (towers.unlocked is empty).
   */
  4: (d) => ({ ...d, towers: { unlocked: [] } }),
  /**
   * v5 (M5) -> v6 (M6): survival records. Per-tier records, totals and history gain M6 statistics (zero / derived
   * defaults via sanitize, e.g. highestWave = bestWave); milestones start empty. Nothing is removed.
   */
  5: (d) => ({ ...d, milestones: [] }),
  /**
   * v6 (M6) -> v7 (M7): headquarters construction (empty expansion structure, stations at their
   * original places, no purchased blueprints) and onboarding. Existing players already know the
   * game: their tutorial is marked complete. Decorations keep their positions.
   */
  /**
   * v7 (M7) -> v8: Warden levels. Veterans start with XP credited from their service record
   * (secured checkpoints, kills, bosses, elites, milestones) so they do not restart at level 1.
   * The skill tree starts unallocated (seed and validation via sanitize).
   */
  /**
   * v10 -> v11: the Rift Level progression (docs/design/progression-design.md). The loot curve changed completely, so
   * progression restarts (owner decision): items, resources, records, levels, tree, HQ construction and market are
   * reset; the profile id, callsign, creation time and tutorial survive. Deterministic (ids and times come from the
   * old document), so the server and every device migrate a stored profile to the same document.
   */
  10: (d) => {
    const p = obj(d.profile);
    const id = typeof p.id === 'string' && p.id ? p.id : 'pf_migrated';
    const at = typeof p.lastSavedAt === 'number' && Number.isFinite(p.lastSavedAt) ? p.lastSavedAt : 0;
    const fresh = createDefaultSave(at, { profileId: id, starterUid: `${id.slice(0, 40)}.rl` });
    const tut = obj(d.tutorial);
    return {
      ...(fresh as unknown as Obj),
      profile: { ...fresh.profile, callsign: typeof p.callsign === 'string' ? p.callsign : fresh.profile.callsign, createdAt: typeof p.createdAt === 'number' ? p.createdAt : at },
      tutorial: { done: arr(tut.done).filter((x) => typeof x === 'string'), skipped: tut.skipped === true },
      wiped: { from: 10, at },
    };
  },
  /** v9 -> v10: two ability slots and an ultimate slot (empty) in the loadout and every preset. */
  9: (d) => ({
    ...d,
    loadout: { ...obj(d.loadout), ability: null, ability2: null, ultimate: null },
    presets: arr(d.presets).map((p) => ({ ...obj(p), slots: { ...obj(obj(p).slots), ability: null, ability2: null, ultimate: null } })),
  }),
  /** v8 -> v9: a secondary weapon slot (empty) in the loadout and in every preset. */
  8: (d) => ({
    ...d,
    loadout: { ...obj(d.loadout), weapon2: null },
    presets: arr(d.presets).map((p) => ({ ...obj(p), slots: { ...obj(obj(p).slots), weapon2: null } })),
  }),
  7: (d) => ({ ...d, progress: { xp: veteranXp(d), tree: { allocated: [] }, respecs: 0 } }),
  6: (d) => ({ ...d, base: { ...obj(d.base), layoutVersion: 2, structure: emptyStructure(), stations: {}, blueprints: [], owned: {} }, tutorial: { done: ['complete'], skipped: false } }),
};


/** XP credited to a v7 profile from its persisted statistics (bounded). */
export function veteranXp(d: Obj): number {
  const t = obj(d.totals);
  const n = (v: unknown) => (typeof v === 'number' && Number.isFinite(v) && v > 0 ? v : 0);
  let checkpoints = 0;
  for (const r of Object.values(obj(d.records))) checkpoints += n(obj(r).checkpoints);
  const ms = arr(d.milestones).length;
  const xp = checkpoints * 300 + n(t.kills) * 2 + n(t.bossesDefeated) * 250 + n(t.elitesDefeated) * 15 + ms * 300;
  return Math.floor(Math.min(5_000_000, xp));
}

export function migrate(data: unknown, fromVersion: number, toVersion = SAVE_VERSION): { data: unknown; ok: boolean } {
  if (!Number.isInteger(fromVersion) || fromVersion < 1 || fromVersion > SAVE_VERSION) return { data, ok: false };
  let cur = obj(data);
  const to = Math.min(SAVE_VERSION, Math.max(fromVersion, Math.floor(toVersion)));
  for (let v = fromVersion; v < to; v++) {
    const step = MIGRATIONS[v];
    if (!step) return { data, ok: false };
    cur = step(cur);
  }
  return { data: cur, ok: true };
}

