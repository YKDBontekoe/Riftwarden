export type RecipeOutput = { kind: 'item'; category: Category; family?: WeaponFamily; moduleBase?: string } | { kind: 'material'; give: Cost; take: Cost };

export interface Recipe {
  id: string;
  name: string;
  group: 'weapons' | 'defense' | 'systems' | 'modules' | 'materials';
  output: RecipeOutput;
  /** Cost multiplier for item recipes (weapons cost more, modules less). */
  costMult: number;
  /** Items produced per craft. */
  quantity: number;
  /** Highest unlocked threat tier required (on top of the quality grade's). */
  unlockTier: number;
  blurb: string;
}

